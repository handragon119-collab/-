START = datetime.date(2026, 6, 24)
DAYS = 10
WINDOWS = [(6, 11), (13, 18), (18, 28)]


def main() -> None:
    random.seed(20260624)
    n = len(A)
    offset = n // len(ACCOUNTS)
    cnt = {acc: 0 for acc in ACCOUNTS}
    entries = []
    for d in range(DAYS):
        date = datetime.datetime(START.year, START.month, START.day) + datetime.timedelta(days=d)
        for w, (h0, h1) in enumerate(WINDOWS):
            for a, acc in enumerate(ACCOUNTS):
                angle = A[(d * 3 + w + a * offset) % n]
                mins = random.randint(h0 * 60, h1 * 60 - 1)
                dt = date + datetime.timedelta(minutes=mins)
                c = cnt[acc]; cnt[acc] += 1
                closer = CLOSERS[(c + a) % len(CLOSERS)]
                pid = f"rcrt-{SHORT[acc]}-d{d:02d}-w{w}"
                paths = cardgen.render_post(acc, pid, angle["cards"],
                                            color_seed=c + a * 4 + 7,
                                            layout_seed=c + a * 2 + 1,
                                            handle=HANDLE[acc])
                entries.append({
                    "id": pid, "username": acc, "topic": angle["topic"],
                    "run_at": dt.strftime("%Y-%m-%d %H:%M"),
                    "text": angle["cap"] + closer,
                    "image_files": paths,
                    "preview_urls": ["/" + p for p in paths],
                })

    existing = []
    if PREPARED.exists():
        try:
            existing = json.loads(PREPARED.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            existing = []
    keep = [e for e in existing if not str(e.get("id", "")).startswith("rcrt-")]
    PREPARED.write_text(json.dumps(keep + entries, ensure_ascii=False, indent=1),
                        encoding="utf-8")
    print(f"✅ 영입 원고 {len(entries)}개 추가 (기존 유지 {len(keep)}개)")


if __name__ == "__main__":
    main()
